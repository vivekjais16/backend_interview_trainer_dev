def make_q(
    slug: str,
    title: str,
    category: str,
    difficulty: str,
    phase: str,
    min_exp: int,
    max_exp: int,
    comp_idx: int,
    freq: int,
    scenario: str,
    analogy: str,
    under_the_hood: str,
    fix: str,
    punchline: str,
    cross_qs: list,
    traps: list,
    best_practices: list,
    mcq_q: str,
    mcq_opts: list,
    mcq_ans: int,
    mcq_exp: str,
    sandbox_type: str = "python",
    code_snippet: str = ""
):
    companies = COMPANIES[comp_idx % len(COMPANIES)]
    theory = f"""### 💡 In Simple Words (The Intuition)
{analogy}

### ⚙️ Under The Hood (Why It Happens)
{under_the_hood}

### 🚀 Step-by-Step Production Fix
{fix}

### 🎯 30-Second MNC Interview Punchline
*"{punchline}"*"""

    q = {
        "title": title,
        "slug": slug,
        "category": category,
        "difficulty": difficulty,
        "phase": phase,
        "min_exp_years": min_exp,
        "max_exp_years": max_exp,
        "company_tags": companies,
        "frequency_score": freq,
        "mindmap_topic": category.replace("_", "-"),
        "mindmap_node": slug.split("-")[0],
        "scenario_text": scenario,
        "theory_explanation": theory,
        "cross_questions": cross_qs,
        "common_traps": traps,
        "best_practices": best_practices,
        "mcq_question": mcq_q,
        "mcq_options": mcq_opts,
        "mcq_correct_index": mcq_ans,
        "mcq_explanation": mcq_exp,
        "has_python_sandbox": sandbox_type == "python",
        "has_sql_sandbox": sandbox_type == "sql",
        "has_redis_sandbox": sandbox_type == "redis",
        "has_nosql_sandbox": sandbox_type == "nosql",
    }

    if sandbox_type == "python":
        q["starter_code"] = code_snippet or "# Write and test your Python solution\n"
        q["solution_code"] = code_snippet or "# Production-grade Python solution\n"
        q["test_cases_json"] = []
    elif sandbox_type == "sql":
        q["sql_schema"] = "ecommerce"
        q["starter_sql"] = code_snippet or "-- Write your SQL query here\n"
        q["solution_sql"] = code_snippet or "-- Optimized query\n"
    elif sandbox_type == "redis":
        q["starter_redis"] = code_snippet or "# Redis commands\n"
        q["solution_redis"] = code_snippet or "# Verified Redis commands\n"
    elif sandbox_type == "nosql":
        q["starter_nosql"] = code_snippet or "db.orders.find({})\n"
        q["solution_nosql"] = code_snippet or "db.orders.find({})\n"

    return q

def write_module(filename: str, var_name: str, questions: list):
    path = os.path.join(BANK_DIR, filename)
    with open(path, "w", encoding="utf-8") as f:
        f.write('"""Autogenerated high-yield technical interview questions."""\n')
        f.write('from app.models.question import QuestionCategory, QuestionDifficulty\n\n')
        f.write(f'{var_name} = [\n')
        for q in questions:
            f.write(f"    {repr(q)},\n")
        f.write(']\n')
    print(f"Created {filename} with {len(questions)} questions.")

